// Bundles src/bridge.ts into one plain ES module for the extension (which has no build step).
// Run after any change under src/: `npm run build`. Commit the output.
import { build } from "esbuild";

await build({
  entryPoints: ["src/bridge.ts"],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  outfile: "../extension/src/agent/address-pipeline.js",
  banner: { js: "// GENERATED by address-pipeline/build.mjs from address-pipeline/src. Do not edit; run `npm run build` there." },
  legalComments: "none",
  logLevel: "info",
});
